def seed():
    with app.app_context():
        added = 0
        for item in SEED_QUOTES:
            if Quote.query.filter_by(text=item["text"]).first():
                continue
            quote = Quote(
                text=item["text"],
                author=item.get("author", "Неизвестен"),
                theme=item.get("theme", ""),
                mood=item.get("mood", ""),
                style=item.get("style", ""),
                lemmas=simple_lemmatize(item["text"]),
            )
            db.session.add(quote)
            added += 1
        db.session.commit()
        print(f"Добавлено новых цитат: {added}")


if __name__ == "__main__":
    seed()